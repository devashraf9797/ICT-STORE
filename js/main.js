// Helper: get translation by key
function t(key) {
  var entry = translations[key];
  if (!entry) return null;
  return entry[currentLang] || entry.en || null;
}

// ==================== LANGUAGE TOGGLE ====================
var langSwitch = document.getElementById('lang-switch');
var currentLang = localStorage.getItem('lang') || 'en';

function updateLang() {
  document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';

  if (langSwitch) {
    langSwitch.textContent = t('lang.switch') || (currentLang === 'en' ? 'العربية' : 'English');
  }

  // Process data-i18n elements (key-based translation)
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      var placeholderKey = key + '.placeholder';
      var placeholderText = t(placeholderKey);
      if (!placeholderText) placeholderText = t(key);
      if (placeholderText) el.placeholder = placeholderText;
    } else {
      var translated = t(key);
      if (translated) el.textContent = translated;
    }
  });

  // Process data-en/data-ar elements (backward compatibility)
  document.querySelectorAll('[data-en]').forEach(function(el) {
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      var attr = 'data-' + currentLang + '-placeholder';
      var placeholder = el.getAttribute(attr);
      if (placeholder) el.placeholder = placeholder;
    } else {
      var text = el.getAttribute('data-' + currentLang);
      if (text) el.textContent = text;
    }
  });

  document.querySelectorAll('[data-en-title]').forEach(function(el) {
    var title = el.getAttribute('data-' + currentLang + '-title');
    if (title) el.title = title;
  });

  localStorage.setItem('lang', currentLang);
}

// ==================== FLOATING BUTTONS ====================
function updateFloatingButtons() {
  var container = document.getElementById('floating-buttons');
  if (container) {
    if (document.documentElement.dir === 'rtl') {
      container.style.right = 'auto';
      container.style.left = '32px';
    } else {
      container.style.right = '32px';
      container.style.left = 'auto';
    }
  }
}

// ==================== CART TEXTS ====================
function updateCartTexts() {
  if (typeof renderCart === 'function') {
    renderCart();
  }
}

// ==================== ADMIN LINK ====================
function checkAdminAccess() {
  var isAdminUser = typeof isAdmin === 'function' && isAdmin();
  document.querySelectorAll('#admin-link').forEach(function(link) {
    link.style.display = isAdminUser ? 'block' : 'none';
  });
}

// ==================== INIT ====================
document.addEventListener('DOMContentLoaded', function() {
  updateLang();
  updateFloatingButtons();
  checkAdminAccess();

  if (langSwitch) {
    langSwitch.addEventListener('click', function() {
      currentLang = currentLang === 'en' ? 'ar' : 'en';
      updateLang();
      updateFloatingButtons();
      updateCartTexts();
    });
  }

  checkAdminAccess();

  if (window.location.hash) {
    var serviceId = window.location.hash.substring(1);
    setTimeout(function() {
      var el = document.getElementById(serviceId);
      if (el) el.scrollIntoView({ behavior: 'smooth' });
    }, 300);
  }
});
